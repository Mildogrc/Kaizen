import { A } from '@solidjs/router';
import { For, createSignal } from 'solid-js';
import { post, useApi } from '../lib/api';
import { attempt } from '../lib/store';
import { Card, Load, Page, Section, SubNav } from '../components/ui';
import { SETTINGS_TABS } from '../lib/nav';

const TOOLS = [
  { href: '/library/imports', label: 'Import content', detail: 'Validate and save items generated by AI or pasted as JSON' },
  { href: '/schemas', label: 'Content types', detail: 'Define the fields and card rules for a kind of material' },
  { href: '/configurations', label: 'Study settings', detail: 'Grammar schedule, character repair, new-card budget, goals' },
];

function GenerateCards(props) {
  const [busy, setBusy] = createSignal(false);
  const run = async () => {
    setBusy(true);
    await attempt(() => post(`/courses/${props.course.id}/generate-cards`), (r) =>
      `Created ${r.cardsCreated} cards and ${r.practiceCreated} practice items${r.ankiSkipped.length ? ` (Anki handles ${r.ankiSkipped.join(', ')})` : ''}.`);
    setBusy(false);
  };
  return <button class="btn btn-sm" disabled={busy()} onClick={run}>{busy() ? 'Making cards…' : 'Make cards'}</button>;
}

export default function SettingsData() {
  const q = useApi(() => '/import');
  return (
    <Page title="Settings" glyph="⚙" subtitle="Tools for the material behind your tracks. You won’t need these to study.">
      <SubNav label="Settings" items={SETTINGS_TABS} />
      <Section title="Tools">
        <Card pad={false}>
          <For each={TOOLS}>
            {(t) => <A href={t.href} class="kz-task"><span class="kz-task__title">{t.label}</span><span class="kz-task__track">{t.detail}</span><span class="kz-task__detail">→</span></A>}
          </For>
        </Card>
      </Section>
      <Load q={q} fallback={<div />}>
        {(d) => (
          <Section title="Make cards from imported material">
            <Card pad={false}>
              <For each={d.courses}>
                {(c) => <div class="kz-task"><span class="kz-task__title">{c.name}</span><span class="kz-task__detail"><GenerateCards course={c} /></span></div>}
              </For>
            </Card>
          </Section>
        )}
      </Load>
    </Page>
  );
}
